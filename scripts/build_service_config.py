"""Write service/pygeoapi-config.yml: one OGC API Features collection per vector item of the STAC catalogue,
served from the PostGIS table that scripts/load_postgis.py creates.

Connection settings are read by pygeoapi from environment variables at start-up, with defaults for a local run:
POSTGRES_HOST, POSTGRES_PORT, POSTGRES_DB, POSTGRES_USER, POSTGRES_PASSWORD, PYGEOAPI_SERVER_URL.

    python scripts/build_service_config.py
"""
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import REPO_URL, SERVICE, SITE_URL, table_name, vector_items  # noqa: E402

HEADER = """# Generated by scripts/build_service_config.py from docs/stac. Do not edit by hand; rebuild instead.
# pygeoapi replaces ${VAR:-default} with the environment variable VAR, or the default when it is not set.
"""


def build():
    resources = {}
    for col, item, _ in vector_items():
        t = table_name(col.id, item.id)
        p = item.properties
        rel = f"stac/{col.id}/{item.id}/{item.id}.json"
        about = [lk.href for lk in col.links if lk.rel == "about"][0]
        resources[t] = {
            "type": "collection",
            "title": p.get("title", item.id),
            "description": p.get("description", ""),
            "keywords": list(col.keywords or []),
            "links": [
                {"type": "application/json", "rel": "describedby", "title": "STAC item", "href": SITE_URL + rel},
                {"type": "text/html", "rel": "related", "title": "Study page", "href": about},
                {"type": "text/html", "rel": "license", "title": col.license, "href":
                    [lk.href for lk in col.links if lk.rel == "license"][0]},
            ],
            "extents": {
                "spatial": {"bbox": [round(x, 6) for x in item.bbox],
                            "crs": "http://www.opengis.net/def/crs/OGC/1.3/CRS84"},
                "temporal": {"begin": p["start_datetime"], "end": p["end_datetime"]},
            },
            "providers": [{
                "type": "feature",
                "name": "PostgreSQL",
                "data": {"host": "${POSTGRES_HOST:-localhost}", "port": "${POSTGRES_PORT:-5432}",
                         "dbname": "${POSTGRES_DB:-geodata}", "user": "${POSTGRES_USER:-postgres}",
                         "password": "${POSTGRES_PASSWORD:-postgres}", "search_path": ["public"]},
                "id_field": "fid",
                "table": t,
                "geom_field": "geom",
                # stored as EPSG:4326 but in longitude, latitude order, i.e. CRS84 (pygeoapi's default storage CRS);
                # declaring EPSG:4326 here would make pygeoapi swap the axes of every coordinate it returns
                "storage_crs": "http://www.opengis.net/def/crs/OGC/1.3/CRS84",
            }],
        }
    return {
        "server": {
            "bind": {"host": "0.0.0.0", "port": 5000},
            "url": "${PYGEOAPI_SERVER_URL:-http://localhost:5000}",
            "mimetype": "application/json; charset=UTF-8",
            "encoding": "utf-8",
            "languages": ["en-US"],
            "cors": True,
            "pretty_print": True,
            "limits": {"default_items": 10, "max_items": 1000},
            "map": {"url": "https://tile.openstreetmap.org/{z}/{x}/{y}.png",
                    "attribution": "&copy; OpenStreetMap contributors"},
        },
        "logging": {"level": "${PYGEOAPI_LOG_LEVEL:-ERROR}"},
        "metadata": {
            "identification": {
                "title": "Open geodata catalogue: OGC API Features",
                "description": ("Vector layers from David Oloyede's open studies, served from PostGIS. The same data "
                                "are listed as a static STAC catalogue at " + SITE_URL),
                "keywords": ["STAC", "OGC API Features", "PostGIS", "hydrology", "Nigeria", "Benin", "Lake Chad", "Mozambique"],
                "keywords_type": "theme",
                "terms_of_service": SITE_URL,
                "url": REPO_URL,
            },
            "license": {"name": "Data: CC BY 4.0 unless a collection states otherwise; code: MIT",
                        "url": "https://creativecommons.org/licenses/by/4.0/"},
            "provider": {"name": "David Oloyede", "url": "https://github.com/oloyededavid"},
            "contact": {"name": "David Oloyede", "url": "https://github.com/oloyededavid", "role": "pointOfContact"},
        },
        "resources": resources,
    }


def main():
    cfg = build()
    out = SERVICE / "pygeoapi-config.yml"
    SERVICE.mkdir(exist_ok=True)
    out.write_text(HEADER + yaml.safe_dump(cfg, sort_keys=False, allow_unicode=True, width=120), encoding="utf-8")
    print(f"wrote {out} with {len(cfg['resources'])} collections")


if __name__ == "__main__":
    main()
